// Regenerates design-system/fonts.css with the IBM Plex woff2 subsets embedded as base64,
// so index.html (opened from disk) and the offline build both render in Plex with no network.
//
//   node tools/embed-fonts.mjs
//
// Fonts: IBM Plex Sans / IBM Plex Mono, (c) IBM Corp., SIL Open Font License 1.1
// (design-system/fonts/OFL-IBM-Plex.txt). Subsets taken from @fontsource/ibm-plex-sans@5.2.8
// and @fontsource/ibm-plex-mono@5.2.7.
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dir = path.join(root, 'design-system', 'fonts');
const RANGES = {
  latin: 'U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD',
  greek: 'U+0370-0377,U+037A-037F,U+0384-038A,U+038C,U+038E-03A1,U+03A3-03FF',
};
const FAMILY = { 'ibm-plex-sans': 'IBM Plex Sans', 'ibm-plex-mono': 'IBM Plex Mono' };

const files = (await fs.readdir(dir)).filter((f) => f.endsWith('.woff2')).sort();
let css = '/* IBM Plex Sans + IBM Plex Mono, (c) IBM Corp., SIL Open Font License 1.1 (fonts/OFL-IBM-Plex.txt).\n'
  + '   Generated by tools/embed-fonts.mjs from design-system/fonts/*.woff2 — do not edit by hand. */\n';
for (const f of files) {
  const m = f.match(/^(ibm-plex-(?:sans|mono))-(latin|greek)-(\d{3})-normal\.woff2$/);
  if (!m) throw new Error('Unexpected font file ' + f);
  const [, fam, subset, weight] = m;
  const b64 = (await fs.readFile(path.join(dir, f))).toString('base64');
  css += `@font-face { font-family: '${FAMILY[fam]}'; font-style: normal; font-weight: ${weight}; font-display: swap; `
    + `src: url(data:font/woff2;base64,${b64}) format('woff2'); unicode-range: ${RANGES[subset]}; }\n`;
}
await fs.writeFile(path.join(root, 'design-system', 'fonts.css'), css);
console.log(`wrote design-system/fonts.css (${files.length} faces, ${(css.length / 1024).toFixed(0)} KB)`);
